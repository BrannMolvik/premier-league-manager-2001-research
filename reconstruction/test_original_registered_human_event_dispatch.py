"""Source-only virtual callback separation, not original queue observation."""
import unittest
from original_registered_human_event_dispatch import (
    EVENT_VTABLE,PAYLOAD_VTABLE, OriginalRegisteredHumanEventError,
    project_source_registered_human_event_timed_call,
    source_new_registered_human_event_due_tick,
    source_registered_human_event_queue_drain_trace,
)
from original_teamselect_queue_lifecycle import (
    OriginalQueueOwnerProjection,project_original_queue_drain,
)

class OriginalRegisteredHumanEventTests(unittest.TestCase):
    def kw(self):
        return dict(native_event_vtable=EVENT_VTABLE,native_payload_vtable=PAYLOAD_VTABLE)

    def test_observed_concrete_type_drain_v4_then_v18_zero_and_unlinks(self):
        ev=source_registered_human_event_queue_drain_trace(77,**self.kw())
        self.assertEqual((ev.first_virtual4_result,ev.repeated_virtual4_result,ev.virtual18_result),
                         (0,None,0))
        # Native queue owner membership is supplied separately, not generated by this helper.
        owner=OriginalQueueOwnerProjection(1,(77,),0,0)
        receipt=project_original_queue_drain(owner,(ev,))
        self.assertEqual(receipt.virtual_call_order,((77,4),(77,24)))
        self.assertEqual(receipt.removed_event_identities,(77,))
        self.assertEqual(receipt.owner.source_event_identities,())
        self.assertNotIn((77,16),receipt.virtual_call_order)

    def test_registered_human_record_creation_is_next_tick_not_immediate(self):
        due=source_new_registered_human_event_due_tick(100)
        self.assertEqual(due,101)
        early=project_source_registered_human_event_timed_call(
            77,native_event_due_tick=due,source_current_tick=100,**self.kw())
        self.assertFalse(early.record_virtual10_invoked)
        now=project_source_registered_human_event_timed_call(
            77,native_event_due_tick=due,source_current_tick=101,**self.kw())
        self.assertTrue(now.record_virtual10_invoked)
        self.assertTrue(now.payload_virtual3c_returned_true)
        self.assertTrue(now.registered_human_handler_413020_called)
        self.assertFalse(now.actual_followup_event_enqueued_verified)

    def test_timed_processor_without_event_due_does_not_call_handler(self):
        for tick in (-1,0,99):
            got=project_source_registered_human_event_timed_call(
                7,native_event_due_tick=100,source_current_tick=tick,**self.kw())
            self.assertFalse(got.registered_human_handler_413020_called)

    def test_source_event_subtype_and_integer_id_mandatory(self):
        for typ in (True,None,3.14,-1):
            with self.subTest(identity=typ),self.assertRaises(OriginalRegisteredHumanEventError):
                source_registered_human_event_queue_drain_trace(typ,**self.kw())
        for changes in (dict(native_event_vtable=0),dict(native_event_vtable=True),
                        dict(native_payload_vtable=0),dict(native_payload_vtable=None)):
            opts={**self.kw(),**changes}
            with self.subTest(changes=changes),self.assertRaises(OriginalRegisteredHumanEventError):
                project_source_registered_human_event_timed_call(
                    5,native_event_due_tick=0,source_current_tick=1,**opts)

    def test_signed_due_time_and_source_overflow_fail_closed(self):
        for val in (True,None,0x80000000,-0x80000001,1.1):
            with self.subTest(value=val),self.assertRaises(OriginalRegisteredHumanEventError):
                source_new_registered_human_event_due_tick(val)
        with self.assertRaises(OriginalRegisteredHumanEventError):
            source_new_registered_human_event_due_tick(0x7fffffff)
        for clock in (None,True,0x80000000):
            with self.subTest(clock=clock),self.assertRaises(OriginalRegisteredHumanEventError):
                project_source_registered_human_event_timed_call(
                    7,native_event_due_tick=10,source_current_tick=clock,**self.kw())

if __name__=='__main__':
    unittest.main()
